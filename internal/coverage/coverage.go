// Package coverage analyzes Go test coverage to identify which code is tested.
package coverage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"golang.org/x/tools/cover"

	"github.com/OpenRAE/go-rae-gremlins/internal/log"

	"github.com/OpenRAE/go-rae-gremlins/internal/configuration"
	"github.com/OpenRAE/go-rae-gremlins/internal/gomodule"
)

// Result contains the Profile generated by the coverage and the time
// it took to generate the coverage report.
type Result struct {
	Profile Profile
	Elapsed time.Duration
}

// Coverage is responsible for executing a Go test with coverage via the Run() method,
// then parsing the result coverage report file.
type Coverage struct {
	cmdContext execContext
	workDir    string
	path       string
	fileName   string
	mod        gomodule.GoModule

	buildTags       string
	coverPkg        string
	integrationMode bool
}

// Option for the Coverage initialization.
type Option func(c *Coverage) *Coverage

type execContext = func(ctx context.Context, name string, args ...string) *exec.Cmd

// New instantiates a Coverage element using exec.CommandContext as execContext,
// actually running the command on the OS.
func New(workdir string, mod gomodule.GoModule, opts ...Option) *Coverage {
	return NewWithCmd(exec.CommandContext, workdir, mod, opts...)
}

// NewWithCmd instantiates a Coverage element given a custom execContext.
func NewWithCmd(cmdContext execContext, workdir string, mod gomodule.GoModule, opts ...Option) *Coverage {
	buildTags := configuration.Get[string](configuration.UnleashTagsKey)
	coverPkg := configuration.Get[string](configuration.UnleashCoverPkgKey)
	integrationMode := configuration.Get[bool](configuration.UnleashIntegrationMode)

	c := &Coverage{
		cmdContext:      cmdContext,
		workDir:         workdir,
		path:            "./...",
		fileName:        "coverage",
		mod:             mod,
		buildTags:       buildTags,
		coverPkg:        coverPkg,
		integrationMode: integrationMode,
	}
	for _, opt := range opts {
		c = opt(c)
	}

	return c
}

// Run executes the coverage command and parses the results, returning a *Profile
// object.
// Before executing the coverage, it downloads the go modules in a separate step.
// This is done to avoid that the download phase impacts the execution time which
// is later used as timeout for the mutant testing execution.
// The cancellation of ctx stops the running command.
func (c *Coverage) Run(ctx context.Context) (Result, error) {
	log.Infof("Gathering coverage... ")
	// The go command runs in the module root, so the profile path must not
	// depend on the directory that resolves it.
	profilePath, err := filepath.Abs(c.filePath())
	if err != nil {
		return Result{}, fmt.Errorf("impossible to resolve the coverage profile path: %w", err)
	}
	if err := c.downloadModules(ctx); err != nil {
		return Result{}, fmt.Errorf("impossible to download modules: %w", err)
	}
	elapsed, err := c.executeCoverage(ctx, profilePath)
	if err != nil {
		return Result{}, fmt.Errorf("impossible to executeCoverage coverage: %w", err)
	}
	log.Infof("done in %s\n", elapsed)
	profile, err := c.profile()
	if err != nil {
		return Result{}, fmt.Errorf("an error occurred while generating coverage profile: %w", err)
	}

	return Result{Profile: profile, Elapsed: elapsed}, nil
}

func (c *Coverage) profile() (_ Profile, err error) {
	cf, err := os.OpenInRoot(c.workDir, c.fileName)
	if err != nil {
		return nil, err
	}
	defer func() {
		err = errors.Join(err, cf.Close())
	}()

	return c.parse(cf)
}

func (c *Coverage) filePath() string {
	return fmt.Sprintf("%v/%v", c.workDir, c.fileName)
}

func (c *Coverage) downloadModules(ctx context.Context) error {
	cmd := c.cmdContext(ctx, "go", "mod", "download")
	cmd.Dir = c.mod.Root
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	return cmd.Run()
}

func (c *Coverage) executeCoverage(ctx context.Context, profilePath string) (time.Duration, error) {
	args := []string{"test"}
	if c.buildTags != "" {
		args = append(args, "-tags", c.buildTags)
	}
	if c.coverPkg != "" {
		args = append(args, "-coverpkg", c.coverPkg)
	}

	args = append(args, "-cover", "-coverprofile", profilePath, c.scanPath())
	cmd := c.cmdContext(ctx, "go", args...)
	cmd.Dir = c.mod.Root

	start := time.Now()
	if out, err := cmd.CombinedOutput(); err != nil {
		log.Infof("\n%s\n", string(out))

		return 0, err
	}

	return time.Since(start), nil
}

func (c *Coverage) scanPath() string {
	path := "./..."
	if !c.integrationMode {
		if c.mod.CallingDir != "." {
			path = fmt.Sprintf("./%s/...", c.mod.CallingDir)
		}
	}

	return path
}

func (c *Coverage) parse(data io.Reader) (Profile, error) {
	profiles, err := cover.ParseProfilesFromReader(data)
	if err != nil {
		return nil, err
	}
	status := make(Profile)
	for _, p := range profiles {
		for _, b := range p.Blocks {
			if b.Count == 0 {
				continue
			}
			block := Block{
				StartLine: b.StartLine,
				StartCol:  b.StartCol,
				EndLine:   b.EndLine,
				EndCol:    b.EndCol,
			}
			fn := c.removeModuleFromPath(p)
			status[fn] = append(status[fn], block)
		}
	}

	return status, nil
}

func (c *Coverage) removeModuleFromPath(p *cover.Profile) string {
	// Remove only the leading module path. A directory can have the name of
	// the module.
	path := strings.TrimPrefix(p.FileName, c.mod.Name+"/")
	path, _ = filepath.Rel(c.mod.CallingDir, path)

	// The engine walks an fs.FS and looks the coverage up by a
	// slash-separated name, but filepath.Rel writes backslashes on Windows.
	return filepath.ToSlash(path)
}
