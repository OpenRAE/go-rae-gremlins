// Package coverage analyzes Go test coverage to identify which code is tested.
package coverage

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"golang.org/x/tools/cover"

	"github.com/OpenRAE/go-rae-gremlins/internal/log"

	"github.com/OpenRAE/go-rae-gremlins/internal/configuration"
	"github.com/OpenRAE/go-rae-gremlins/internal/gomodule"
	"github.com/OpenRAE/go-rae-gremlins/internal/process"
)

// Result contains the Profile generated by the coverage, the time it took
// to generate the coverage report, and the peak memory in bytes of the
// largest process of the coverage run.
type Result struct {
	Profile Profile
	Elapsed time.Duration
	Peak    uint64
}

// Coverage is responsible for executing a Go test with coverage via the Run() method,
// then parsing the result coverage report file.
type Coverage struct {
	cmdContext execContext
	workDir    string
	buildCache string
	path       string
	fileName   string
	mod        gomodule.GoModule

	buildTags       string
	coverPkg        string
	integrationMode bool
}

// Option for the Coverage initialization.
type Option func(c *Coverage) *Coverage

type execContext = func(ctx context.Context, name string, args ...string) *exec.Cmd

// New instantiates a Coverage element using exec.CommandContext as execContext,
// actually running the command on the OS. Each go command uses buildCache,
// an absolute path, as its Go build cache.
func New(workdir, buildCache string, mod gomodule.GoModule, opts ...Option) *Coverage {
	return NewWithCmd(exec.CommandContext, workdir, buildCache, mod, opts...)
}

// NewWithCmd instantiates a Coverage element given a custom execContext.
func NewWithCmd(
	cmdContext execContext, workdir, buildCache string, mod gomodule.GoModule, opts ...Option,
) *Coverage {
	buildTags := configuration.Get[string](configuration.UnleashTagsKey)
	coverPkg := configuration.Get[string](configuration.UnleashCoverPkgKey)
	integrationMode := configuration.Get[bool](configuration.UnleashIntegrationMode)

	c := &Coverage{
		cmdContext:      cmdContext,
		workDir:         workdir,
		buildCache:      buildCache,
		path:            "./...",
		fileName:        "coverage",
		mod:             mod,
		buildTags:       buildTags,
		coverPkg:        coverPkg,
		integrationMode: integrationMode,
	}
	for _, opt := range opts {
		c = opt(c)
	}

	return c
}

// Run executes the coverage command and parses the results, returning a *Profile
// object.
// Before executing the coverage, it downloads the go modules and builds the
// packages and their dependencies into the cache in separate steps.
// This is done to avoid that the download and the build of the dependencies
// impact the execution time which is later used as timeout for the mutant
// testing execution.
// The cancellation of ctx stops the running command.
func (c *Coverage) Run(ctx context.Context) (Result, error) {
	log.Infof("Gathering coverage... ")
	// The go command runs in the module root, so the profile path must not
	// depend on the directory that resolves it.
	profilePath, err := filepath.Abs(c.filePath())
	if err != nil {
		return Result{}, fmt.Errorf("impossible to resolve the coverage profile path: %w", err)
	}
	if err := c.downloadModules(ctx); err != nil {
		return Result{}, fmt.Errorf("impossible to download modules: %w", err)
	}
	if err := c.buildDependencies(ctx); err != nil {
		return Result{}, fmt.Errorf("impossible to build the packages: %w", err)
	}
	elapsed, peak, err := c.executeCoverage(ctx, profilePath)
	if err != nil {
		return Result{}, fmt.Errorf("impossible to executeCoverage coverage: %w", err)
	}
	log.Infof("done in %s\n", elapsed)
	profile, err := c.profile()
	if err != nil {
		return Result{}, fmt.Errorf("an error occurred while generating coverage profile: %w", err)
	}

	return Result{Profile: profile, Elapsed: elapsed, Peak: peak}, nil
}

func (c *Coverage) profile() (_ Profile, err error) {
	cf, err := os.OpenInRoot(c.workDir, c.fileName)
	if err != nil {
		return nil, err
	}
	defer func() {
		err = errors.Join(err, cf.Close())
	}()

	return c.parse(cf)
}

func (c *Coverage) filePath() string {
	return fmt.Sprintf("%v/%v", c.workDir, c.fileName)
}

// goCommand returns a go command with args that runs in the module root
// and uses the Go build cache of c.
func (c *Coverage) goCommand(ctx context.Context, args ...string) *exec.Cmd {
	cmd := c.cmdContext(ctx, "go", args...)
	cmd.Dir = c.mod.Root
	// exec.Cmd uses the last value of a duplicate variable, so GOCACHE
	// replaces the value in the environment of Gremlins.
	cmd.Env = append(cmd.Environ(), "GOCACHE="+c.buildCache)

	return cmd
}

func (c *Coverage) downloadModules(ctx context.Context) error {
	cmd := c.goCommand(ctx, "mod", "download")
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	return process.Run(cmd)
}

// buildDependencies compiles the packages of the scan path, their tests, and
// all their dependencies into the build cache. The go list command compiles
// the packages for their export data, and it does not link or run a test.
// The go test command does not stamp VCS information, so go list does not
// read it either: a VCS error must not fail a module that go test can test.
func (c *Coverage) buildDependencies(ctx context.Context) error {
	args := []string{"list", "-buildvcs=false", "-export", "-deps", "-test"}
	if c.buildTags != "" {
		args = append(args, "-tags", c.buildTags)
	}
	args = append(args, c.scanPath())
	cmd := c.goCommand(ctx, args...)

	// A nil Stdout drops the package list to the null device.
	var output bytes.Buffer
	cmd.Stderr = &output

	if err := process.Run(cmd); err != nil {
		log.Infof("\n%s\n", output.String())

		return err
	}

	return nil
}

func (c *Coverage) executeCoverage(ctx context.Context, profilePath string) (time.Duration, uint64, error) {
	args := []string{"test"}
	if c.buildTags != "" {
		args = append(args, "-tags", c.buildTags)
	}
	if c.coverPkg != "" {
		args = append(args, "-coverpkg", c.coverPkg)
	}

	args = append(args, "-count=1", "-cover", "-coverprofile", profilePath, c.scanPath())
	cmd := c.goCommand(ctx, args...)

	var output bytes.Buffer
	cmd.Stdout = &output
	cmd.Stderr = &output

	start := time.Now()
	usage, err := process.RunBounded(cmd, 0)
	if err != nil {
		log.Infof("\n%s\n", output.String())

		return 0, 0, err
	}

	return time.Since(start), usage.Peak, nil
}

func (c *Coverage) scanPath() string {
	path := "./..."
	if !c.integrationMode {
		if c.mod.CallingDir != "." {
			path = fmt.Sprintf("./%s/...", c.mod.CallingDir)
		}
	}

	return path
}

func (c *Coverage) parse(data io.Reader) (Profile, error) {
	profiles, err := cover.ParseProfilesFromReader(data)
	if err != nil {
		return nil, err
	}
	status := make(Profile)
	for _, p := range profiles {
		for _, b := range p.Blocks {
			if b.Count == 0 {
				continue
			}
			block := Block{
				StartLine: b.StartLine,
				StartCol:  b.StartCol,
				EndLine:   b.EndLine,
				EndCol:    b.EndCol,
			}
			fn := c.removeModuleFromPath(p)
			status[fn] = append(status[fn], block)
		}
	}

	return status, nil
}

func (c *Coverage) removeModuleFromPath(p *cover.Profile) string {
	// Remove only the leading module path. A directory can have the name of
	// the module.
	path := strings.TrimPrefix(p.FileName, c.mod.Name+"/")
	path, _ = filepath.Rel(c.mod.CallingDir, path)

	// The engine walks an fs.FS and looks the coverage up by a
	// slash-separated name, but filepath.Rel writes backslashes on Windows.
	return filepath.ToSlash(path)
}
